// 每晚結束的時間：投影片用它算出最後一段有多長
export const classEnd = '21:15';

// 今晚流程每一段的長度（分鐘）：用下一段的開始時間，最後一段用 classEnd
export function agendaWithMinutes(agenda) {
  const toMin = (t) => {
    const [h, m] = t.split(':').map(Number);
    return h * 60 + m;
  };
  return agenda.map(([time, label], i) => {
    const end = i + 1 < agenda.length ? agenda[i + 1][0] : classEnd;
    return { time, end, label, minutes: toMin(end) - toMin(time) };
  });
}

